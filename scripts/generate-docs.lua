-- Generates docs/commands.md and docs/configuration.md from the plugin source.
-- Run from the repository root: nvim --headless --clean -l scripts/generate-docs.lua
-- Fails when a command or exported function has no description, so new API cannot go undocumented.

vim.opt.rtp:prepend(vim.fn.getcwd())

local GENERATED_NOTICE = "<!-- Generated by scripts/generate-docs.lua from the plugin source. Do not edit by hand. -->"

local errors = {}
local function fail(msg) table.insert(errors, msg) end

local function write(path, lines) vim.fn.writefile(vim.split(table.concat(lines, "\n"), "\n"), path) end

local function sorted_keys(t)
  local keys = vim.tbl_keys(t)
  table.sort(keys)
  return keys
end

local function escape_cell(text) return (text:gsub("|", "\\|")) end

---------------------------------------------------------------------------
-- Commands and Lua API
---------------------------------------------------------------------------

local commands = require("easy-dotnet.commands")

---@return { path: string[], command: easy-dotnet.Command }[]
local function collect_commands()
  local result = {}
  local function walk(tbl, path)
    for _, name in ipairs(sorted_keys(tbl)) do
      local command = tbl[name]
      if type(command) == "table" then
        local full = vim.list_extend(vim.deepcopy(path), { name })
        if command.handle then table.insert(result, { path = full, command = command }) end
        if command.subcommands then walk(command.subcommands, full) end
      end
    end
  end
  walk(commands, {})
  return result
end

local function lua_name(path) return table.concat(path, "_") end

local function lua_access(name)
  if name:match("^[%a_][%w_]*$") then return "dotnet." .. name end
  return string.format('dotnet["%s"]', name)
end

local function lua_params(args)
  if not args then return "" end
  local name = args:match("^<(.+)>$")
  if name then return name end
  name = args:match("^%[(.+)%]$")
  if name then return name .. "?" end
  return args
end

-- Functions defined directly in lua/easy-dotnet/init.lua rather than generated from commands
local module_functions = {
  setup = { params = "opts?", desc = "Configures the plugin, see [Configuration](./configuration.md)" },
  try_get_selected_solution = { params = "", desc = "Returns `{ basename: string, path: string }` for the selected solution" },
  create_item = { params = "path", desc = "Spawns a picker for creating a new file from a template in the given directory (used by the file explorer integrations)" },
  stop = { params = "", desc = "Stops running workspace sessions" },
  create_new_item = { deprecated = true },
}

local function generate_commands_doc()
  local all = collect_commands()
  local public, internal = {}, {}
  for _, entry in ipairs(all) do
    local cmd = "Dotnet " .. table.concat(entry.path, " ")
    if not entry.command.desc then fail("command `" .. cmd .. "` has no desc in lua/easy-dotnet/commands.lua") end
    table.insert(entry.path[1]:sub(1, 1) == "_" and internal or public, entry)
  end

  local function command_rows(entries)
    local rows = { "| Command | Description |", "| --- | --- |" }
    for _, entry in ipairs(entries) do
      local cmd = ":Dotnet " .. table.concat(entry.path, " ") .. (entry.command.args and (" " .. entry.command.args) or "")
      table.insert(rows, string.format("| `%s` | %s |", cmd, escape_cell(entry.command.desc or "")))
    end
    return rows
  end

  local lines = {
    GENERATED_NOTICE,
    "",
    "# Commands",
    "",
    "Every `:Dotnet` command is also available as a Lua function, see [Lua API](#lua-api). Run `:Dotnet` without arguments to pick a command.",
    "",
    "**Legend**",
    "",
    "- `<Picker>`: the configured picker (`snacks`, `fzf`, `telescope`, or the basic fallback)",
    "- `<Picker Default>`: picker selection that persists for future use",
    "- `<DArgs>`: dotnet args (e.g. `--no-build`, `--configuration release`). Always optional",
    "- `<sln>`: solution file (in some cases a `.csproj` or `.fsproj` is used as fallback if no `.sln` file exists)",
    "",
    "## Vim commands",
    "",
  }
  vim.list_extend(lines, command_rows(public))
  vim.list_extend(lines, { "", "## Internal commands", "", "Server maintenance commands, mostly useful when troubleshooting.", "" })
  vim.list_extend(lines, command_rows(internal))

  vim.list_extend(lines, {
    "",
    "## Lua API",
    "",
    "The command functions are registered by `setup()`.",
    "",
    "```lua",
    'local dotnet = require("easy-dotnet")',
    "```",
    "",
    "| Function | Description |",
    "| --- | --- |",
  })

  local rows = {}
  local command_names = {}
  for _, entry in ipairs(public) do
    local name = lua_name(entry.path)
    command_names[name] = true
    rows[name] = string.format("| `%s(%s)` | %s |", lua_access(name), lua_params(entry.command.args), escape_cell(entry.command.desc or ""))
  end

  local dotnet = require("easy-dotnet")
  for name, value in pairs(dotnet) do
    if type(value) == "function" and not command_names[name] then
      local info = module_functions[name]
      if not info then
        fail("exported function `" .. name .. "` has no entry in module_functions in scripts/generate-docs.lua")
      elseif not info.deprecated then
        rows[name] = string.format("| `dotnet.%s(%s)` | %s |", name, info.params, escape_cell(info.desc))
      end
    end
  end
  for _, name in ipairs(sorted_keys(rows)) do
    table.insert(lines, rows[name])
  end

  vim.list_extend(lines, {
    "",
    "Workspace diagnostics can also be requested with a severity filter:",
    "",
    "```lua",
    'local diagnostics = require("easy-dotnet").diagnostics',
    "diagnostics.get_workspace_diagnostics() -- configured default severity",
    'diagnostics.get_workspace_diagnostics("error") -- errors only',
    'diagnostics.get_workspace_diagnostics("warning") -- errors and warnings',
    "```",
    "",
  })
  write("docs/commands.md", lines)
end

---------------------------------------------------------------------------
-- Configuration: default options, keymaps, highlight groups
---------------------------------------------------------------------------

local function default_options_block()
  local source = vim.fn.readfile("lua/easy-dotnet/options.lua")
  local start_index, end_index
  for i, line in ipairs(source) do
    if line:match("%-%- docs:defaults:start") then start_index = i end
    if line:match("%-%- docs:defaults:end") then end_index = i end
  end
  if not start_index or not end_index then
    fail("docs:defaults markers not found in lua/easy-dotnet/options.lua")
    return {}
  end
  local block = { "```lua", 'require("easy-dotnet").setup({' }
  for i = start_index + 1, end_index - 1 do
    -- defaults sit at 4 spaces inside options.lua; re-indent to 2 inside setup({ ... })
    table.insert(block, (source[i]:gsub("^    ", "  ")))
  end
  vim.list_extend(block, { "})", "```" })
  return block
end

local function keymap_table(mappings, option_prefix, filter)
  local rows = { "| Key | Option | Action |", "| --- | --- | --- |" }
  for _, name in ipairs(sorted_keys(mappings)) do
    if not filter or filter(name) then
      local mapping = mappings[name]
      table.insert(rows, string.format("| `%s` | `%s.%s` | %s |", escape_cell(mapping.lhs), option_prefix, name, escape_cell(mapping.desc or "")))
    end
  end
  return rows
end

local function generate_keymaps()
  local options = require("easy-dotnet.options").options
  local test_mappings = options.test_runner.mappings
  local is_buffer = function(name) return name:match("_from_buffer$") ~= nil end

  local lines = {
    "## Keymaps",
    "",
    "Override any of these in `setup()` with `{ lhs = ..., desc = ... }`.",
    "",
    "### Test runner window",
    "",
  }
  vim.list_extend(lines, keymap_table(test_mappings, "test_runner.mappings", function(name) return not is_buffer(name) end))
  vim.list_extend(lines, { "", "### Test files", "", "Active in buffers with discovered tests.", "" })
  vim.list_extend(lines, keymap_table(test_mappings, "test_runner.mappings", is_buffer))
  vim.list_extend(lines, { "", "### Managed terminal", "" })
  vim.list_extend(lines, keymap_table(options.managed_terminal.mappings, "managed_terminal.mappings"))
  vim.list_extend(lines, { "", "### Outdated packages", "" })
  vim.list_extend(lines, keymap_table(options.outdated.mappings, "outdated.mappings"))
  vim.list_extend(lines, { "", "### Debugger", "" })
  vim.list_extend(lines, keymap_table(options.debugger.mappings, "debugger.mappings"))
  return lines
end

local function describe_highlight(opts)
  if opts.link then return "links to `" .. opts.link .. "`" end
  local parts = {}
  for _, key in ipairs({ "fg", "bg" }) do
    if opts[key] then table.insert(parts, key .. " `" .. tostring(opts[key]) .. "`") end
  end
  for _, key in ipairs({ "bold", "italic", "underline" }) do
    if opts[key] then table.insert(parts, key) end
  end
  return table.concat(parts, ", ")
end

local function generate_highlights()
  -- Record what highlights.define() sets instead of applying it
  local recorded = {}
  local set_hl = vim.api.nvim_set_hl
  vim.api.nvim_set_hl = function(_, name, opts) recorded[name] = opts end
  require("easy-dotnet.highlights").define()
  vim.api.nvim_set_hl = set_hl

  local plugin_groups, semantic_links = {}, {}
  for _, name in ipairs(sorted_keys(recorded)) do
    table.insert(name:match("^@") and semantic_links or plugin_groups, name)
  end

  local lines = {
    "## Highlight groups",
    "",
    "Defined on setup and re-applied on `ColorScheme`.",
    "",
    "| Highlight group | Default |",
    "| --- | --- |",
  }
  for _, name in ipairs(plugin_groups) do
    table.insert(lines, string.format("| `%s` | %s |", name, describe_highlight(recorded[name])))
  end
  vim.list_extend(lines, {
    "",
    "### Semantic token links",
    "",
    "Set with `default = true`, so colorschemes and your own highlights take precedence.",
    "",
    "| Highlight group | Default |",
    "| --- | --- |",
  })
  for _, name in ipairs(semantic_links) do
    table.insert(lines, string.format("| `%s` | %s |", name, describe_highlight(recorded[name])))
  end
  return lines
end

local function generate_configuration_doc()
  local lines = {
    GENERATED_NOTICE,
    "",
    "# Configuration",
    "",
    "All options are optional. Pass only the ones you want to change to `setup()`.",
    "",
    "## Default options",
    "",
  }
  vim.list_extend(lines, default_options_block())
  table.insert(lines, "")
  vim.list_extend(lines, generate_keymaps())
  table.insert(lines, "")
  vim.list_extend(lines, generate_highlights())
  table.insert(lines, "")
  write("docs/configuration.md", lines)
end

generate_commands_doc()
generate_configuration_doc()

if #errors > 0 then
  io.stderr:write("generate-docs failed:\n  " .. table.concat(errors, "\n  ") .. "\n")
  os.exit(1)
end
print("Generated docs/commands.md and docs/configuration.md")
